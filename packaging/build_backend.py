"""Assemble application source/assets without projects, research data or credentials.

Usage: python packaging/build_backend.py --destination <installation>/backend
Runtime/model provisioning and per-install configuration are separate operations.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import shutil

SOURCE = Path(__file__).resolve().parents[1]


def selected_files(root=SOURCE):
    files = {root/'desktop_backend.py', root/'inference_windowless.py'}
    files.update((root/'app').rglob('*.py'))
    files.update(p for p in (root/'app/studio_assets').iterdir()
                 if p.is_file() and p.suffix in {'.html','.css','.js'})
    files.update(p for p in (root/'app/web/models').iterdir() if p.suffix in {'.json','.joblib'})
    # Superseded, unreferenced bass classifier; production always loads v2.
    files.discard(root/'app/web/models/bass_voice_v1.joblib')
    files.discard(root/'app/web/models/bass_voice_v1.json')
    files.update(p for p in (root/'app/web/vendor').iterdir() if any(word in p.name.lower() for word in ('license','notice')))
    files.update(p for p in (root/'frontend').iterdir() if p.is_file() and p.suffix in {'.js','.css','.html','.svg','.png','.ico'})
    files.update(p for p in (root/'inference').iterdir() if p.is_file() and p.suffix in {'.py','.json','.txt','.md'})
    # The frozen model checks its shipped self-test vectors at load time too.
    files.update(p for p in (root/'inference/model').rglob('*')
                 if p.is_file() and p.suffix in {'.py','.json','.txt','.md','.npz','.lab'})
    files.update(root.glob('LICENSE*'))
    files.update(root.glob('NOTICE*'))
    # Runtime paths are generated by configure.py, never copied from the developer.
    files.discard(root/'inference/runtime.local.json')
    return sorted(p for p in files if p.is_file() and '__pycache__' not in p.parts)


def build(destination, root=SOURCE):
    destination = Path(destination).resolve()
    if destination == root.resolve() or root.resolve().is_relative_to(destination):
        raise ValueError('Destination must not contain the source checkout')
    if destination.exists() and any(destination.iterdir()):
        raise ValueError('Use a new empty staging directory; existing installations are not overwritten')
    files = []
    for source in selected_files(root):
        relative = source.relative_to(root)
        target = destination/relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        files.append(dict(path=relative.as_posix(), bytes=target.stat().st_size,
                          sha256=hashlib.sha256(target.read_bytes()).hexdigest()))
    # The manifest records code/weights before generated installation configuration.
    (destination/'application-files.json').write_text(json.dumps({'schema':1,'files':files},indent=2),encoding='utf8')
    return dict(files=len(files), bytes=sum(f['bytes'] for f in files))


if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--destination', type=Path, required=True)
    args=p.parse_args()
    print(json.dumps(build(args.destination)))
